-- embedding 调用审计：两阶段写（先 pending 再终态），写入路径唯一。
-- 调用前预写失败 → **不得**发出该次 embedding 请求（原则 V fail-closed）。
CREATE TABLE IF NOT EXISTS embedding_calls (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        text        REFERENCES runs(run_id),
    ingest_job_id text        REFERENCES kb_ingest_jobs(ingest_job_id),
    model         text        NOT NULL,
    dimensions    integer     NOT NULL,
    input_count   integer     NOT NULL,              -- 本次提交的文本条数
    prompt_tokens bigint      NOT NULL DEFAULT 0,
    status        text        NOT NULL,              -- pending / success / failed / unknown
    error_kind    text,
    created_at    bigint      NOT NULL,
    finished_at   bigint,
    CHECK (status IN ('pending', 'success', 'failed', 'unknown')),
    CHECK (input_count >= 1),
    CHECK (num_nonnulls(run_id, ingest_job_id) <= 1)  -- 二选一或都不填（启动期回填可为空）
);

