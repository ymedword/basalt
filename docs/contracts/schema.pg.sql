CREATE UNIQUE INDEX IF NOT EXISTS idx_config_snapshots_hash ON config_snapshots(agent_name, hash);

-- ============================================================
-- 审计一：LLM 调用（既有表演进：purpose）
-- ============================================================

CREATE TABLE IF NOT EXISTS llm_calls (
    id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            text        NOT NULL,
    session_id        text,
    round             integer     NOT NULL,
    provider          text        NOT NULL,
    model             text        NOT NULL,
    prompt_tokens     bigint      NOT NULL DEFAULT 0,
    completion_tokens bigint      NOT NULL DEFAULT 0,
    total_tokens      bigint      NOT NULL DEFAULT 0,
    duration_ms       bigint      NOT NULL,
    status            text        NOT NULL,   -- pending / success / failed / unknown
    error_message     text,
    error_kind        text,
    config_hash       text,
    created_at        bigint      NOT NULL,
    purpose           text        NOT NULL DEFAULT 'chat', -- 新增：chat / rerank / summary / embedding / compaction
    -- compaction = 会话压缩的摘要调用（C-25 强制预写 pending 审计）；缺这一值会让摘要
