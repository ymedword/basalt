CREATE TABLE IF NOT EXISTS compaction_entries (
    compaction_id           text        PRIMARY KEY,
    scope_session_id        text        REFERENCES sessions(session_id),
    scope_run_id            text        REFERENCES runs(run_id),
    chain_epoch             integer     NOT NULL,     -- 链代次，从 1 起；重建根 = 同 scope 最大值 + 1
    parent_compaction_id    text        REFERENCES compaction_entries(compaction_id),
    trigger_run_id          text        NOT NULL REFERENCES runs(run_id),
    attempt_id              text        NOT NULL,     -- 一次尝试一行；重提**必须**换新值
    -- 消息标识是**字面量**而非外键：会话范围是 messages.id 的十进制串，无状态范围是
    -- `msg/<runID>/<pos>`（§3.1.11）——后者在 messages 表里没有对应行，bigint + 外键
    -- 会把无状态条目整条挡在门外。顺序（covered_from ≤ cut < first_kept）由引擎的切点
    -- 判定与测试保证，不用列间 CHECK（text 的字典序不等于消息顺序）。
    covered_from_message_id text        NOT NULL,
    cut_message_id          text        NOT NULL,
    first_kept_message_id   text        NOT NULL,
    strategy_version        text        NOT NULL,
    prompt_version          text        NOT NULL,
    model                   text        NOT NULL,
    prompt_tokens           bigint      NOT NULL DEFAULT 0,
    completion_tokens       bigint      NOT NULL DEFAULT 0,
    tokens_before           bigint      NOT NULL DEFAULT 0,
    tokens_after            bigint      NOT NULL DEFAULT 0,
    status                  text        NOT NULL,     -- committed / failed / stale
    reason_code             text,
    source_refs             jsonb       NOT NULL DEFAULT '[]'::jsonb, -- 审计集（含被剔除 / 此后失效的引用）
    included_refs           jsonb       NOT NULL DEFAULT '[]'::jsonb, -- 当前依赖集（included_refs ⊆ source_refs）
    summary                 text,                     -- 派生文本；**不建全文索引、不参与历史检索**
    created_at              bigint      NOT NULL,
    stale_at                bigint,
    UNIQUE (attempt_id),
    CHECK (num_nonnulls(scope_session_id, scope_run_id) = 1),
    CHECK (chain_epoch >= 1),
    CHECK (status IN ('committed', 'failed', 'stale')),
    CHECK (status <> 'stale' OR stale_at IS NOT NULL),
    CHECK (parent_compaction_id IS NULL OR parent_compaction_id <> compaction_id)
);

-- 幂等身份（attempt_id） / 链代次（chain_epoch） / 当前有效头（同 epoch 同覆盖范围至多一份 committed）三者分开。
-- 两条部分唯一索引只是最后防线，不是收敛机制：多列唯一键只排斥**完全相等**的切点，
-- 串行与"不产生重叠根 / 分叉链"由 Append 的 scope 级 pg_advisory_xact_lock + 锁内链资格选头负责。
CREATE UNIQUE INDEX IF NOT EXISTS ux_compaction_session_head
    ON compaction_entries(scope_session_id, chain_epoch, covered_from_message_id, cut_message_id)
    WHERE scope_session_id IS NOT NULL AND status = 'committed';
CREATE UNIQUE INDEX IF NOT EXISTS ux_compaction_run_head
    ON compaction_entries(scope_run_id, chain_epoch, covered_from_message_id, cut_message_id)
    WHERE scope_run_id IS NOT NULL AND status = 'committed';

CREATE INDEX IF NOT EXISTS idx_compaction_session_created
    ON compaction_entries(scope_session_id, created_at);
CREATE INDEX IF NOT EXISTS idx_compaction_run_created
    ON compaction_entries(scope_run_id, created_at);
CREATE INDEX IF NOT EXISTS idx_compaction_parent
    ON compaction_entries(parent_compaction_id);
