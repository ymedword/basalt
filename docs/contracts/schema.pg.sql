-- 循环外键：kb_documents.latest_version_id → kb_document_versions.version_id。
-- 两表互引，只能在两者都建好之后补约束；用 DO 块保证幂等。
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_kb_documents_latest_version'
    ) THEN
        ALTER TABLE kb_documents
            ADD CONSTRAINT fk_kb_documents_latest_version
            FOREIGN KEY (latest_version_id) REFERENCES kb_document_versions(version_id);
    END IF;
END $$;

