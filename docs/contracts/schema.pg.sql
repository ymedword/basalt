-- Basalt 数据库结构契约（PostgreSQL）
--
-- 契约地位：本文档是 Basalt **PostgreSQL 谱系**（v1）表 / 列 / 约束 / 状态字面量的唯一事实源。
--   它与 docs/contracts/schema.sql（SQLite 谱系，v6 **冻结**）**并列**，不是替代关系：
--   两者是不同的谱系字面量，SQLite 侧自本 US 起只作迁移源，不再新增迁移。
--   与 schema.sql 同名的表，列语义以 schema.sql 的历史注解决定，本文档只补本谱系的类型、
--   约束与增量列；两份文件出现分歧时按本文件头部「谱系差异裁决」处理。
-- 目标 schema_version：1（PostgreSQL 谱系自 1 起；SQLite 的 6 不得混用——原则 IX / FR-071）。
--
-- 谱系差异裁决（与 schema.sql 逐条对应，不擅自"统一"）：
--   D1. 时间：两个谱系同为 **Unix 毫秒 UTC 整数**——SQLite 存 `INTEGER`，本谱系存 `bigint`。
--       **不得**改用 `timestamptz` / `now()`（设计 C-13 / C-14）：`storage_cutover.first_write_at`
--       由 `MarkFirstWrite` 写 `at.UTC().UnixMilli()` 的 BIGINT 毫秒，列类型不符即写错类型；
--       `TestPostgres_TimeColumnsAreUnixMillisUTC` 扫描全库时间列的列类型，出现 `timestamptz` 即失败。
--       两谱系表示一致 → SQLite v6 迁移逐值无损、无需时区换算；对外 API 同为 Unix 毫秒
--       （FR-026 / FR-076），仓储层不做毫秒 ↔ 时间戳转换。
--   D2. 布尔：SQLite 存 INTEGER 0/1；本谱系用原生 `boolean`。
--   D3. 自增主键：SQLite `INTEGER PRIMARY KEY AUTOINCREMENT` → `bigint GENERATED BY DEFAULT AS
--       IDENTITY`。迁移导入时必须能写入原值，导入后由迁移器执行
--       `ALTER TABLE ... ALTER COLUMN <col> RESTART WITH <max+1>` 校正序列。
--   D4. JSON 列分两类，**不得**混用：
--       a. 「字节即身份」的清单列保持 `text`——`config_snapshots.manifest_json`、
--          `run_resource_manifests.snapshot_json`、`resource_versions.manifest_json`、
--          `agent_archives.manifest_json`。这些列的 sha256 是内容身份，`jsonb` 会重排键与空白，
--          破坏"hash 由本列内容派生"的既有语义。
--       b. 结构化查询列用 `jsonb`——`management_operations.detail_json`、
--          `compaction_entries.source_refs` / `included_refs`、`context_assembly_records.*`、
--          `diagnostic_events.attrs`。
--   D5. 二进制：SQLite `BLOB` → `bytea`（`credentials_versions.nonce` / `ciphertext`）。
--   D6. 全文检索：SQLite 无生成列配置要求；本谱系 `kb_chunks.tsv` / `messages.tsv` 为
--       `STORED` 生成列，配置必须写成 immutable 形式 `to_tsvector('simple'::regconfig, ...)`
--       （用稳定函数或非字面量 regconfig 会被 PostgreSQL 拒绝）。
--   D7. 扩展：`vector` 与 `pg_trgm` 由 DBA 在库级预装，**不由本脚本创建**（应用账号非超级用户，
--       见 R-01 实测）；启动校验在 `internal/storage/postgres/connect.go` 里 fail-closed 检查。
--
-- 迁移纪律（本谱系）：
--   1. 建表 / 建索引一律 `IF NOT EXISTS`（幂等）；结构变更 = 新增受控前向迁移 + 递增本谱系版本号
--   2. 迁移在单事务内执行并先取 `pg_advisory_xact_lock(<固定键>)`；并发启动的第二个进程等待或超时失败
--   3. 已发布迁移只追加，**不得**改写；本文件对应 v1 基线，发布后冻结
--   4. 已发布迁移里**不得**出现 `DROP TABLE` / `DROP COLUMN` / 类型收窄；破坏性变更只能新增列 / 新增表
--   5. 事务不得跨 LLM 调用与工具执行（与 schema.sql 纪律 7 同）
--   6. 本文件的逐字副本是运行时迁移源 `internal/storage/postgres/migrations/0001_postgres_v1.sql`，
--      契约测试 `TestPostgresSchemaFile_MatchesContract` 断言两者字节一致
--
-- 向量维度冻结（D-05 实测，2026-10-28）：
--   `vector(512)`，cosine，写入前 L2 归一化；索引代际 1 = **精确扫描，不建 ANN**（D-06）。
--   证据：dev-env/evidence/d05-embedding-eval.json（FullRecall@10 1.0000 / nDCG@10 0.9344 /
--   p95 312 ms，AI 标注评测）。换维度**必须**新增同结构表（如 `kb_chunk_embeddings_d1024`）
--   并走版本化迁移；**不得**在同一 `vector(n)` 列混写不同维度，也不得改成无维度 `vector`。

-- ============================================================
-- 版本与迁移
-- ============================================================

CREATE TABLE IF NOT EXISTS schema_version (
    version     integer     PRIMARY KEY,      -- 迁移版本号，逐版递增（本谱系自 1 起）
    applied_at  bigint      NOT NULL,         -- 应用时间（UTC）
    description text        NOT NULL          -- 该版本做了什么（迁移文件路径）
);

-- ============================================================
-- 调用方（新增；身份与配额的根）
-- ============================================================
-- 内置 `local-admin` 行在首次建库 / 迁移时**必须** upsert（kind='builtin'、无限额度）；
-- sessions / runs / scheduled_tasks 的 caller_id 外键指向本表。
-- status 控制整体停用；停用不删行（历史归属必须仍可解析）。

CREATE TABLE IF NOT EXISTS callers (
    caller_id  text        PRIMARY KEY,       -- cal_ + 26 位 Crockford Base32（ULID 形态）；local-admin 为固定字面量
    kind       text        NOT NULL,          -- builtin / service
    name       text        NOT NULL,          -- 展示名；不参与身份
    project    text        NOT NULL DEFAULT '', -- 归属项目；空串 = 不限
    status     text        NOT NULL DEFAULT 'active', -- active / disabled
    created_at bigint      NOT NULL,
    CHECK (kind IN ('builtin', 'service')),
    CHECK (status IN ('active', 'disabled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_callers_name ON callers(project, name);

-- ============================================================
-- 会话与消息（既有表演进：消息来源引用见 message_evidence_refs）
-- ============================================================

CREATE TABLE IF NOT EXISTS sessions (
    session_id     text        PRIMARY KEY,   -- channel+user+profile 联合派生
    profile_name   text        NOT NULL,      -- 关联 Agent（Profile 名 = 目录名）
    channel        text        NOT NULL,      -- cli / web / scheduler
    user_id        text        NOT NULL,
    status         text        NOT NULL DEFAULT 'active', -- active / archived
    message_count  bigint      NOT NULL DEFAULT 0,
    created_at     bigint      NOT NULL,
    last_active_at bigint      NOT NULL,
    archived_at    bigint,
    caller_id      text        REFERENCES callers(caller_id)  -- 新增：NULL = 迁移遗留的无归属会话，只允许管理面读取
);

CREATE INDEX IF NOT EXISTS idx_sessions_profile ON sessions(profile_name);
CREATE INDEX IF NOT EXISTS idx_sessions_status  ON sessions(status, last_active_at DESC);
CREATE INDEX IF NOT EXISTS idx_sessions_caller  ON sessions(caller_id, last_active_at DESC);

CREATE TABLE IF NOT EXISTS messages (
    id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        text        NOT NULL REFERENCES sessions(session_id),
    run_id            text,                   -- 产生该消息的 Run（system 注入类可为空）
    seq               integer     NOT NULL,   -- 会话内序号（1 起，追加序）
    role              text        NOT NULL,   -- system / user / assistant / tool
    content           text,                   -- 可空：带工具调用的 assistant 消息 content 可能为空
    tool_calls        text,                   -- JSON 数组：[{id,name,arguments}]（arguments 是 JSON 字符串，原样保存）
    tool_call_id      text,
    reasoning_content text,
    provider_extra    text,
    created_at        bigint      NOT NULL,
    -- 历史关键词检索（生成列：配置必须是 immutable 形式，见 D6）
    tsv               tsvector GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, coalesce(content, ''))) STORED
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_messages_session_seq ON messages(session_id, seq);
CREATE INDEX IF NOT EXISTS idx_messages_run ON messages(run_id);
CREATE INDEX IF NOT EXISTS idx_messages_tsv ON messages USING gin (tsv);
CREATE INDEX IF NOT EXISTS idx_messages_content_trgm ON messages USING gin (content gin_trgm_ops);

-- ============================================================
-- Run（执行与审计的单位；既有表演进：归属与授权来源）
-- ============================================================

CREATE TABLE IF NOT EXISTS runs (
    run_id           text        PRIMARY KEY, -- <channel>-<unix_millis>-<随机6位>
    session_id       text,                    -- 无状态调用可为空
    agent            text        NOT NULL,
    channel          text        NOT NULL,    -- cli / web / scheduler / admin
    user_id          text        NOT NULL,
    trigger          text        NOT NULL,    -- user / cron / manual / api
    status           text        NOT NULL,    -- running / completed / limit_reached / cancelled / failed
    reason           text,
    iterations       integer     NOT NULL DEFAULT 0,
    tool_calls       integer     NOT NULL DEFAULT 0,
    config_hash      text,
    started_at       bigint      NOT NULL,
    finished_at      bigint,
    -- 新增列：归属调用方 + 最近一次执行者 + 执行授权来源
    caller_id        text        NOT NULL REFERENCES callers(caller_id),
    authorizing_kind text        NOT NULL,    -- caller-key / admin-builtin
    key_id           text,                    -- authorizing_kind='caller-key' 时非空
    reservation_id   text,                    -- 准入预留（Run 级 Chat 预算）；可空；**不设**唯一约束
    actor            text        NOT NULL,    -- caller / scheduler / recovery / admin-cli
    CHECK (authorizing_kind IN ('caller-key', 'admin-builtin')),
    CHECK ((authorizing_kind = 'caller-key') = (key_id IS NOT NULL)),
    CHECK ((authorizing_kind = 'admin-builtin') = (caller_id = 'local-admin')),
    CHECK (actor IN ('caller', 'scheduler', 'recovery', 'admin-cli'))
);

CREATE INDEX IF NOT EXISTS idx_runs_session  ON runs(session_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_runs_agent    ON runs(agent, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_runs_status   ON runs(status) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS idx_runs_caller   ON runs(caller_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_runs_reservation ON runs(reservation_id) WHERE reservation_id IS NOT NULL;

