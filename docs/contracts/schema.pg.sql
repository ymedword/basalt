-- ============================================================
-- 定时任务（既有表演进：创建时固定归属与授权来源）
-- ============================================================

CREATE TABLE IF NOT EXISTS scheduled_tasks (
    task_id             text        PRIMARY KEY,
    agent_name          text        NOT NULL,
    cron                text        NOT NULL, -- 6 段表达式（秒 分 时 日 月 周）
    zone                text        NOT NULL, -- IANA 时区名，缺省 UTC
    message             text        NOT NULL,
    deliver_to          text        NOT NULL DEFAULT '',
    enabled             boolean     NOT NULL DEFAULT true,
    definition_hash     text        NOT NULL,
    last_run_at         bigint,
    last_status         text,
    retired_at          bigint,
    created_at          bigint      NOT NULL,
    updated_at          bigint      NOT NULL,
    -- 新增列：归属与执行授权来源（调度执行**不得**改写）
    caller_id           text        NOT NULL REFERENCES callers(caller_id),
    authorizing_kind    text        NOT NULL, -- caller-key / admin-builtin
    authorizing_key_id  text,                 -- caller-key 时非空；执行前重读**这一把** Key
    CHECK (authorizing_kind IN ('caller-key', 'admin-builtin')),
    CHECK ((authorizing_kind = 'caller-key') = (authorizing_key_id IS NOT NULL)),
    CHECK ((authorizing_kind = 'admin-builtin') = (caller_id = 'local-admin'))
);

CREATE INDEX IF NOT EXISTS idx_scheduled_tasks_agent ON scheduled_tasks(agent_name);
CREATE INDEX IF NOT EXISTS idx_scheduled_tasks_caller ON scheduled_tasks(caller_id);

