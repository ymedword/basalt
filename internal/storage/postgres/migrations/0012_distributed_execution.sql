-- Basalt 数据库迁移（PostgreSQL 谱系 v11 → v12）
--
-- 分布式执行增量（US-24 / FR-24-01 / FR-24-28）：Worker 身份登记、执行权租约、
-- 租约状态转换记录、定时触发的数据库领取列与去重索引、跨 Worker 取消标志、
-- `resource_kind` 闭集加入 `agent_bundle`，以及诊断原因码闭集加入
-- `recovery_unknown`（A1 接管收尾的"未重放动作"证据）。
--
-- 为什么是前向迁移：`docs/contracts/schema.pg.sql` 与 `0001_postgres_v1.sql` 是
-- 已发布的 v1 基线（二者逐字节相等），迁移纪律只追加、不得回头改写；
-- 既有库实际应用的是 v1..v11，新结构只能以 0012 追加。`schema.pg.sql` 本 US 不动。
--
-- 纪律：
--   * 迁移运行器以**无参数** `ExecContext` 执行脚本（internal/storage/postgres/migrate.go），
--     任何 `$1` 占位符都会直接报错——本文件不出现参数占位符。
--   * 全部 DDL 幂等（IF NOT EXISTS / DROP IF EXISTS + ADD），重复执行不报错、不重复建对象。
--   * 回填只处理"进程已不在"的在途行（停机迁移口径），租约写成**立即过期**，
--     由首个新 Worker 的回收器按 A 类规则领取收尾；不回填任何关闭态 Flow 根。
--   * 时间列一律 bigint Unix 毫秒（UTC），时间值取 `(extract(epoch from now()) * 1000)::bigint`：
--     `now()` 在同一事务内恒定，三类回填共用同一迁移时刻。
--
-- 约束名说明：`resource_versions` / `resource_pointers` 的 `resource_kind` 内联 CHECK
-- 由 PostgreSQL 自动命名。本文件使用的三个名字已在隔离 schema 应用 0001–0011 后按
-- `pg_constraint` 实测确认（2026-11-06，查询见模块卡 §3.4 末）；名字若在任何目标库上
-- 对不上，`DROP IF EXISTS` 静默空转、随后 `ADD CONSTRAINT` 会因旧约束仍在而
-- 在插入期暴露——不保留"看起来成功、实际没生效"的中间态。

-- ============================================================
-- Worker 身份登记（FR-24-01）：心跳只作诊断，存活判定只用租约过期。
-- ============================================================

CREATE TABLE IF NOT EXISTS worker_nodes (
    instance_id       text        PRIMARY KEY,
    worker_name       text        NOT NULL,
    hostname          text        NOT NULL,
    build_version     text        NOT NULL,
    schema_version    integer     NOT NULL,
    started_at        bigint      NOT NULL,
    last_heartbeat_at bigint      NOT NULL,
    stopped_at        bigint
);
CREATE INDEX IF NOT EXISTS idx_worker_nodes_heartbeat ON worker_nodes(last_heartbeat_at);

-- ============================================================
-- 执行权唯一权威（FR-24-04 / FR-24-35）：(kind, resource_id) 主键即"一类资源一行"。
-- kind 闭集 fail-closed：未知 kind 不能落库。
-- ============================================================

CREATE TABLE IF NOT EXISTS execution_leases (
    kind            text        NOT NULL CHECK (kind IN ('run','schedule_execution','flow_root')),
    resource_id     text        NOT NULL,
    owner_worker_id text        NOT NULL,
    ownership_epoch bigint      NOT NULL CHECK (ownership_epoch >= 0),
    acquired_at     bigint      NOT NULL,
    renewed_at      bigint      NOT NULL,
    expires_at      bigint      NOT NULL,
    released_at     bigint,
    PRIMARY KEY (kind, resource_id)
);
-- 回收扫描的两支谓词是"已到期（未释放）"**或**"已释放但业务未终态"，
-- 因此索引**不带**部分谓词：带 WHERE released_at IS NULL 只能覆盖前一支。
CREATE INDEX IF NOT EXISTS idx_execution_leases_expiry
    ON execution_leases(expires_at);

-- ============================================================
-- 租约状态转换记录（FR-24-26 运维面）：只记状态转换，不记每次续约。
-- 它不是审计结论——审计权威仍是既有 llm_calls 与管理操作表。
-- ============================================================

CREATE TABLE IF NOT EXISTS lease_events (
    event_id                 bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                     text    NOT NULL,
    resource_id              text    NOT NULL,
    event                    text    NOT NULL CHECK (event IN
        ('claimed','takeover','released','renew_failed','reclaimed')),
    owner_worker_id          text    NOT NULL,
    ownership_epoch          bigint  NOT NULL,
    previous_owner_worker_id text,
    previous_epoch           bigint,
    detail                   text    NOT NULL DEFAULT '',
    occurred_at              bigint  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_lease_events_resource
    ON lease_events(kind, resource_id, occurred_at DESC);

-- ============================================================
-- 定时触发的数据库领取（FR-24-10 / FR-24-12 / FR-24-13）
-- ============================================================

ALTER TABLE scheduled_tasks ADD COLUMN IF NOT EXISTS next_fire_at bigint;
CREATE INDEX IF NOT EXISTS idx_scheduled_tasks_due
    ON scheduled_tasks(next_fire_at) WHERE enabled AND retired_at IS NULL;

ALTER TABLE task_executions ADD COLUMN IF NOT EXISTS planned_at bigint;
ALTER TABLE task_executions ADD COLUMN IF NOT EXISTS owner_worker_id text;
ALTER TABLE task_executions ADD COLUMN IF NOT EXISTS ownership_epoch bigint;
-- 一次计划触发只有一条执行行；manual 触发 planned_at 为 NULL，不受此约束。
CREATE UNIQUE INDEX IF NOT EXISTS ux_task_executions_cron_planned
    ON task_executions(task_id, planned_at)
    WHERE trigger = 'cron' AND planned_at IS NOT NULL;
-- 同一任务同时最多一条未收尾执行（跨 Worker 的任务互斥）。
-- 字面量是 'started'：task_executions.status 只有 started/completed/failed/skipped，
-- 没有 'running'；该列无 CHECK，写错不报错、只会让索引永远匹配不到行。
CREATE UNIQUE INDEX IF NOT EXISTS ux_task_executions_active
    ON task_executions(task_id) WHERE status = 'started';

-- 投递行的执行归属（B2 的所有权判据）：Prepare 与 pending 行同一事务写入；
-- 迁移遗留行与历史已结算行为 NULL，B2 对 NULL 退回按 task_id 判。
-- 类型必须是 bigint：指向 task_executions.id（identity bigint）。
ALTER TABLE schedule_deliveries ADD COLUMN IF NOT EXISTS execution_id bigint;
CREATE INDEX IF NOT EXISTS idx_schedule_deliveries_execution
    ON schedule_deliveries(execution_id) WHERE status = 'pending';

-- ============================================================
-- 资源发布闭集扩展（FR-24-24 / FR-24-25）：resource_kind 由三类扩到四类。
-- 只改列级 CHECK 不够——复合 CHECK 的 skill 支必须同时放宽到 agent_bundle，
-- 否则 agent_bundle 落不进任何一支，INSERT 直接违反它。
-- ============================================================

ALTER TABLE resource_versions
    DROP CONSTRAINT IF EXISTS resource_versions_resource_kind_check;
ALTER TABLE resource_versions
    ADD CONSTRAINT resource_versions_resource_kind_check
    CHECK (resource_kind IN ('model_connection', 'mcp_server', 'skill', 'agent_bundle'));

ALTER TABLE resource_versions
    DROP CONSTRAINT IF EXISTS resource_versions_check;
ALTER TABLE resource_versions
    ADD CONSTRAINT resource_versions_check CHECK (
        (resource_kind IN ('model_connection', 'mcp_server') AND definition_yaml IS NOT NULL)
        OR (resource_kind IN ('skill', 'agent_bundle')
            AND manifest_json IS NOT NULL AND storage_path IS NOT NULL)
    );

ALTER TABLE resource_pointers
    DROP CONSTRAINT IF EXISTS resource_pointers_resource_kind_check;
ALTER TABLE resource_pointers
    ADD CONSTRAINT resource_pointers_resource_kind_check
    CHECK (resource_kind IN ('model_connection', 'mcp_server', 'skill', 'agent_bundle'));

-- ============================================================
-- 跨 Worker 取消标志（FR-24-22）：非属主只写标志，属主在续约 / 检查点观察。
-- ============================================================

ALTER TABLE runs ADD COLUMN IF NOT EXISTS cancel_requested boolean NOT NULL DEFAULT false;
CREATE INDEX IF NOT EXISTS idx_runs_caller_running
    ON runs(caller_id) WHERE status = 'running';

-- ============================================================
-- 在途行回填（FR-24-28）：旧进程已不在（停机迁移），由首个新 Worker 的回收器
-- 立即领取收尾。expires_at 取迁移时刻而不是 now()+ttl——遗留租约应当**立即**
-- 可被接管，留出 ttl 只会让"升级后仍无人收尾"的窗口变长。
-- owner='legacy' 不是合法 Worker，任何 Renew / 提交都必然失权。
-- ============================================================

INSERT INTO execution_leases(kind, resource_id, owner_worker_id, ownership_epoch,
                             acquired_at, renewed_at, expires_at, released_at)
SELECT 'run', run_id, 'legacy', 0,
       (extract(epoch from now()) * 1000)::bigint,
       (extract(epoch from now()) * 1000)::bigint,
       (extract(epoch from now()) * 1000)::bigint,
       NULL
  FROM runs WHERE status = 'running'
ON CONFLICT (kind, resource_id) DO NOTHING;

INSERT INTO execution_leases(kind, resource_id, owner_worker_id, ownership_epoch,
                             acquired_at, renewed_at, expires_at, released_at)
SELECT 'schedule_execution', id::text, 'legacy', 0,
       (extract(epoch from now()) * 1000)::bigint,
       (extract(epoch from now()) * 1000)::bigint,
       (extract(epoch from now()) * 1000)::bigint,
       NULL
  FROM task_executions WHERE status = 'started'
ON CONFLICT (kind, resource_id) DO NOTHING;

-- 非终态 Flow **根**必须一并回填；但 flow_tasks 同时存根与子任务，只按 status
-- 过滤会给每个子任务也建 flow_root 租约（子任务不是根，必须由父根推进）。
-- 关闭态根（cancelling / 带关闭意图 / 已过 deadline）**不回填**：它们由
-- sweepClosures 推进、不领租约，回填只会留下没人碰的死行。
INSERT INTO execution_leases(kind, resource_id, owner_worker_id, ownership_epoch,
                             acquired_at, renewed_at, expires_at, released_at)
SELECT 'flow_root', task_id, 'legacy', 0,
       (extract(epoch from now()) * 1000)::bigint,
       (extract(epoch from now()) * 1000)::bigint,
       (extract(epoch from now()) * 1000)::bigint,
       NULL
  FROM flow_tasks
 WHERE status IN ('queued','running','blocked')
   AND cancel_requested = false
   AND close_intent = 'none'
   AND parent_task_id IS NULL
   AND root_task_id = task_id
   AND depth = 0
   AND deadline > (extract(epoch from now()) * 1000)::bigint
ON CONFLICT (kind, resource_id) DO NOTHING;

-- ============================================================
-- 诊断原因码值域扩展（FR-24-26 / 模块卡 §2.3.5 A1）
-- ============================================================
-- A1 接管收尾要把"已发出、结果不可知且不会重放"的未完成动作写成诊断事件；
-- 原因码 `recovery_unknown` 是这条证据的分类。值域约束由 0006 以内联 CHECK 建立，
-- 而 0006 已发布、不得改写，因此在这里以"先删后建"前向扩展到新值域。
-- 值列表必须与 `internal/diagnostics` 的 `allReasonCodes` 以及
-- `docs/contracts/openapi.yaml` 的 `DiagnosticReasonCode` 逐字一致
-- （`TestDiagnostics_ContractFields` 与 `TestMigrations_...` 判卷）。
-- `NOT VALID` 沿用 0006 的口径：历史行保持可读，约束只作用于新写入。
ALTER TABLE diagnostic_events DROP CONSTRAINT IF EXISTS diagnostic_events_reason_code_check;
ALTER TABLE diagnostic_events ADD CONSTRAINT diagnostic_events_reason_code_check CHECK
    (reason_code IS NULL OR reason_code IN ('','vector_unavailable','keyword_unavailable',
     'rerank_timeout','permission_denied','budget_trimmed','history_trimmed','no_answer',
     'citation_unresolved','chunker_failed','embed_failed','index_failed','key_revoked',
     'quota_exhausted','rate_limited','migration_verify_failed','llm_call_failed',
     'concurrency_limited','chunk_invalidated','recovery_unknown')) NOT VALID;
