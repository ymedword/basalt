package dbmigrate

// 本文件用**两份冻结契约**判卷声明类型映射（颗粒度文档 §2.11.1 的映射表）：
// 源列声明类型 → 目标类型与编码标签必须与 `docs/contracts/schema.sql` +
// `docs/contracts/schema.pg.sql` 逐列相符；`columnTypeOverrides` 只允许覆盖
// "族不同"的那几列，多一条少一条都失败。
//
// 为什么是白盒测试：映射函数与覆盖表都不导出，判卷点必须在包内；对外行为由
// `export_test.go` 的导出回合覆盖。
// This white-box test cross-checks the declared-type mapping against both frozen
// contracts; the override table must be exactly the set of columns whose naive mapping
// changes type family.

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// contractPaths 是两份契约的相对路径（相对本包目录）。
var contractPaths = struct{ SQLite, PostgreSQL string }{
	SQLite:     filepath.Join("..", "..", "docs", "contracts", "schema.sql"),
	PostgreSQL: filepath.Join("..", "..", "docs", "contracts", "schema.pg.sql"),
}

// sqlConstraintKeywords 是表体里**非列定义**条目的起始关键字。
var sqlConstraintKeywords = map[string]bool{
	"primary":    true,
	"unique":     true,
	"foreign":    true,
	"check":      true,
	"constraint": true,
}

// sqlColumnStopKeywords 结束列声明类型的第一个关键字。
// `GENERATED` 让 `bigint GENERATED BY DEFAULT AS IDENTITY` 只取到 `bigint`。
var sqlColumnStopKeywords = map[string]bool{
	"primary":    true,
	"not":        true,
	"null":       true,
	"default":    true,
	"unique":     true,
	"check":      true,
	"references": true,
	"collate":    true,
	"generated":  true,
	"as":         true,
}

// TestDeclaredType_MatchesContracts 逐表逐列对拍：源列必须能映射、映射结果必须与
// PG 契约同族、编码标签必须与目标列的存储类一致；覆盖表必须恰好等于"族不同"的列集合。
// 逆改点：给映射表加一条新族（如把 INTEGER 改成 numeric）→ 族断言红；删掉
// `scheduled_tasks.enabled` 覆盖 → 该列族断言红；加一条用不上的覆盖 → 集合断言红。
func TestDeclaredType_MatchesContracts(t *testing.T) {
	sqlite := parseContract(t, contractPaths.SQLite)
	postgres := parseContract(t, contractPaths.PostgreSQL)

	needed := make(map[string]bool)
	for _, table := range migrationOrder {
		sourceColumns, ok := sqlite[table]
		require.True(t, ok, "SQLite 契约缺少源表 %q", table)
		targetColumns, ok := postgres[table]
		require.True(t, ok, "PG 契约缺少源表 %q", table)
		require.NotEmpty(t, sourceColumns, "表 %q 在 SQLite 契约里没有列", table)

		for _, column := range sortedNames(sourceColumns) {
			decl := sourceColumns[column]
			contractType, ok := targetColumns[column]
			require.True(t, ok,
				"PG 契约缺少 %s.%s（源声明 %q）——导出会带上目标没有的列", table, column, decl)

			naiveType, _, err := mapDeclaredType(decl)
			require.NoErrorf(t, err, "%s.%s 的声明类型 %q 没有目标类型", table, column, decl)

			mappedType, mappedTag, err := mapColumnType(table, column, decl)
			require.NoErrorf(t, err, "%s.%s 的声明类型 %q 没有映射", table, column, decl)

			require.Equal(t, typeClass(contractType), typeClass(mappedType),
				"%s.%s：源声明 %q 映射成 %q，但契约声明 %q", table, column, decl, mappedType, contractType)
			require.Equal(t, tagForClass(typeClass(contractType)), mappedTag,
				"%s.%s：编码标签必须与目标列存储类一致（契约 %q）", table, column, contractType)

			key := table + "." + column
			if typeClass(naiveType) == typeClass(contractType) {
				require.Equal(t, naiveType, mappedType,
					"%s：族已一致，覆盖表不得再插手", key)
				continue
			}
			// 族不同：只允许由覆盖表钉死，且覆盖结果必须与契约逐字相等。
			require.Equal(t, contractType, mappedType,
				"%s：覆盖结果必须与契约声明逐字相等", key)
			_, overridden := columnTypeOverrides[key]
			require.True(t, overridden,
				"%s：源声明 %q 与契约 %q 不同族，必须在 columnTypeOverrides 里显式钉死",
				key, decl, contractType)
			needed[key] = true
		}
	}

	declared := make(map[string]bool, len(columnTypeOverrides))
	for key := range columnTypeOverrides {
		declared[key] = true
	}
	require.Equal(t, needed, declared,
		"覆盖表必须恰好是族不同的列集合（多出 = 过期条目，缺少 = 漏钉）")
}

// parseContract 把一份契约 DDL 解析成 表名 → 列名 → 规范化声明类型。
// 只认 `CREATE TABLE IF NOT EXISTS`；条目不认识的形态直接失败，**不**静默跳过。
func parseContract(t *testing.T, path string) map[string]map[string]string {
	t.Helper()
	raw, err := os.ReadFile(path)
	require.NoErrorf(t, err, "契约文件必须存在：%s", path)

	text := stripSQLComments(string(raw))
	const prefix = "CREATE TABLE IF NOT EXISTS "
	tables := make(map[string]map[string]string)

	for {
		index := strings.Index(text, prefix)
		if index < 0 {
			break
		}
		rest := text[index+len(prefix):]
		open := strings.IndexByte(rest, '(')
		require.Greater(t, open, 0, "%s：CREATE TABLE 后缺列定义括号", path)
		name := strings.TrimSpace(rest[:open])
		body, tail := splitParenBody(t, path, rest[open:])

		columns := make(map[string]string)
		for _, item := range splitTopLevel(t, body) {
			column, decl, isColumn := parseColumnItem(t, path, name, item)
			if !isColumn {
				continue
			}
			require.NotContains(t, columns, column,
				"%s：表 %q 的列 %q 出现两次（契约自身矛盾）", path, name, column)
			columns[column] = decl
		}
		require.NotEmpty(t, columns, "%s：表 %q 没解析出任何列", path, name)
		tables[name] = columns
		text = tail
	}
	require.NotEmpty(t, tables, "%s：没解析出任何表——解析口径与契约格式已漂移", path)
	return tables
}

// parseColumnItem 解析表体内的一条：约束条目返回 isColumn=false。
func parseColumnItem(t *testing.T, path, table, item string) (column, decl string, isColumn bool) {
	t.Helper()
	fields := strings.Fields(item)
	require.NotEmptyf(t, fields, "%s：表 %q 出现空条目", path, table)

	first := strings.ToLower(fields[0])
	if sqlConstraintKeywords[first] {
		return "", "", false
	}
	require.Regexpf(t, `^[a-z][a-z0-9_]*$`, fields[0],
		"%s：表 %q 的条目 %q 不像列定义（解析口径漂移时必须显式失败）", path, table, item)

	types := make([]string, 0, 2)
	for _, field := range fields[1:] {
		if sqlColumnStopKeywords[strings.ToLower(field)] {
			break
		}
		types = append(types, field)
	}
	require.NotEmptyf(t, types, "%s：表 %q 的列 %q 没有声明类型", path, table, fields[0])
	return fields[0], normalizeDeclType(strings.Join(types, " ")), true
}

// normalizeDeclType 统一声明类型写法：小写、去长度 / 精度参数、压平空白。
func normalizeDeclType(decl string) string {
	normalized := strings.ToLower(strings.Join(strings.Fields(decl), " "))
	if index := strings.IndexByte(normalized, '('); index >= 0 {
		normalized = strings.TrimSpace(normalized[:index])
	}
	return normalized
}

// stripSQLComments 去掉 `--` 行注释；单引号串内的 `--` 原样保留。
func stripSQLComments(sql string) string {
	var out strings.Builder
	out.Grow(len(sql))
	inQuote := false
	for i := 0; i < len(sql); i++ {
		c := sql[i]
		if inQuote {
			out.WriteByte(c)
			if c != '\'' {
				continue
			}
			// 成对单引号是串内转义，仍留在串里。
			if i+1 < len(sql) && sql[i+1] == '\'' {
				out.WriteByte(sql[i+1])
				i++
				continue
			}
			inQuote = false
			continue
		}
		switch {
		case c == '\'':
			inQuote = true
			out.WriteByte(c)
		case c == '-' && i+1 < len(sql) && sql[i+1] == '-':
			for i < len(sql) && sql[i] != '\n' {
				i++
			}
			out.WriteByte('\n')
		default:
			out.WriteByte(c)
		}
	}
	return out.String()
}

// splitParenBody 取 `(` 起第一个括号内部的文本与右括号之后的剩余。
func splitParenBody(t *testing.T, path, text string) (body, rest string) {
	t.Helper()
	require.Truef(t, strings.HasPrefix(text, "("), "%s：期望列定义以 ( 开头", path)

	depth := 0
	inQuote := false
	for i := 0; i < len(text); i++ {
		c := text[i]
		if inQuote {
			if c != '\'' {
				continue
			}
			if i+1 < len(text) && text[i+1] == '\'' {
				i++
				continue
			}
			inQuote = false
			continue
		}
		switch c {
		case '\'':
			inQuote = true
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return text[1:i], text[i+1:]
			}
		}
	}
	require.FailNowf(t, "列定义括号不闭合", "%s", path)
	return "", ""
}

// splitTopLevel 按顶层逗号切分（括号与单引号串内的逗号不切）。
func splitTopLevel(t *testing.T, body string) []string {
	t.Helper()

	var (
		items   []string
		current strings.Builder
		depth   int
		inQuote bool
	)
	for i := 0; i < len(body); i++ {
		c := body[i]
		if inQuote {
			current.WriteByte(c)
			if c != '\'' {
				continue
			}
			if i+1 < len(body) && body[i+1] == '\'' {
				current.WriteByte(body[i+1])
				i++
				continue
			}
			inQuote = false
			continue
		}
		switch c {
		case '\'':
			inQuote = true
			current.WriteByte(c)
		case '(':
			depth++
			current.WriteByte(c)
		case ')':
			depth--
			current.WriteByte(c)
		case ',':
			if depth != 0 {
				current.WriteByte(c)
				continue
			}
			items = append(items, current.String())
			current.Reset()
		default:
			current.WriteByte(c)
		}
	}
	require.Zero(t, depth, "表体括号不平衡，切分结果不可信")
	require.False(t, inQuote, "表体单引号不闭合，切分结果不可信")
	if tail := strings.TrimSpace(current.String()); tail != "" {
		items = append(items, tail)
	}
	return items
}

// typeClass 把 PG 类型归到存储族：族相同才允许"由声明类型直接推出"，
// 族不同必须走覆盖表。
func typeClass(pgType string) string {
	switch strings.ToLower(strings.TrimSpace(pgType)) {
	case "bigint", "integer", "smallint", "int":
		return "integer"
	case "text", "varchar", "character varying", "char":
		return "text"
	case "bytea":
		return "bytes"
	case "double precision", "real":
		return "real"
	case "numeric", "decimal":
		return "numeric"
	case "boolean", "bool":
		return "boolean"
	case "json", "jsonb":
		return "json"
	default:
		return "unknown:" + pgType
	}
}

// tagForClass 给出目标族对应的编码标签（NULL 之外的四类）。
func tagForClass(class string) ValueTag {
	switch class {
	case "integer", "boolean":
		return TagInteger
	case "text", "json", "numeric":
		return TagText
	case "real":
		return TagReal
	case "bytes":
		return TagBytes
	default:
		return ""
	}
}

// sortedNames 返回列名的字典序副本（判卷输出稳定）。
func sortedNames(columns map[string]string) []string {
	names := make([]string, 0, len(columns))
	for name := range columns {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
