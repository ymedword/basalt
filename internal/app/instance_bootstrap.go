package app

// 本文件是「新实例」判定与首次配置生成（14D T089，颗粒度文档 §2.5.1）。
//
// 判定口径**只有一条**：`<工作区>/.basalt/basalt.db` 与 `<工作区>/.basalt/instance.json`
// 都不存在，才是新实例。库里已经有数据但它只是没写 YAML 的存量实例，**不得**当成新实例
// 放宽预算或补生成密钥——那等于替运维改了上限、还替它造了一把新钥匙。
//
// 生成次序也是判据的一部分：配置先写、名册后写。这样"名册在、配置不在"只可能由异常
// 中断造成，而"配置在、名册不在"会被下一次启动继续当作新实例补写名册——反向次序会让
// 一次崩溃永久跳过一次配置生成。
//
// The only definition of a new instance is that neither the database nor the roster
// exists. The config is written before the roster, so a crash can never mark an
// instance as established while its config was skipped.

import (
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/ymedword/basalt/internal/builtin"
)

// instanceConfigTemplate 是新实例的最小可用配置（T089）。四处取值都有出处：
//   - `budget.max_iterations: 30` 覆盖五个内置 Agent 的最大需求（模块卡 §2.5.1 的预算
//     兼容检查：核心缺省 10 会截断需要更多轮次的剧本）；
//   - `server.max_concurrent_runs: 32` 与 core 缺省同值，写成显式是让运维看得见；
//   - `http.admin_auth.mode: token` 且**不写** `token`：密码由实例私有目录的
//     `admin-token` 提供（T090），明文凭据禁止落盘；
//   - `shell.allowed_commands` 登记随包运行时组件的发行布局路径：内置 MCP 条目的 command
//     是绝对路径，而命令白名单整串逐字比对——不登记时两条免凭据条目会在 spawn 前被策略
//     拒绝，开箱即用走不到"依赖就位"（14D §2.2.2 显式登记口径，清单产者属 US-17 拟）。
//     路径与内置安装器**同源**（`builtinRuntimePaths` → `builtin.AllowlistedCommands`）：
//     两边各算一份迟早对不上。取不到程序目录时整节省略——不猜路径，回落到显式登记。
//
// instanceConfigTemplate is the minimal working configuration for a new instance; every
// value is documented in the module card.
func instanceConfigTemplate(runtimeRoot, wsRoot string) string {
	if runtimeRoot == "" {
		return instanceConfigTemplateHead
	}
	var body strings.Builder
	body.WriteString(instanceConfigTemplateHead)
	body.WriteString(shellAllowlistComment)
	body.WriteString("shell:\n  allowed_commands:\n")
	for _, command := range builtin.AllowlistedCommands(builtinRuntimePaths(runtimeRoot, wsRoot)) {
		body.WriteString("    - " + yamlSingleQuoted(command) + "\n")
	}
	return body.String()
}

// instanceConfigTemplateHead 是配置模板里与运行时布局无关的部分。
// instanceConfigTemplateHead is the layout-independent part of the template.
const instanceConfigTemplateHead = `# 由 basalt 在全新实例首次启动时生成；已有配置文件一律不改写。
# Generated by basalt on the first start of a provably new instance. An existing
# configuration file is never rewritten.
http:
  addr: 127.0.0.1:8080
  admin_auth:
    mode: token
server:
  max_concurrent_runs: 32
budget:
  max_iterations: 30
`

// shellAllowlistComment 解释白名单为什么带绝对路径、为什么生成时就写死。
// shellAllowlistComment explains why the allowlist carries absolute paths.
const shellAllowlistComment = `# 随包运行时组件按发行布局登记：命令白名单整串逐字比对，未登记的命令在 spawn 前被拒绝。
# Bundled runtime components are registered by their release-layout paths; the command
# allowlist compares the whole string, so an unregistered command is denied before spawn.
`

// yamlSingleQuoted 把路径写成 YAML 单引号标量：单引号内反斜杠是字面量（Windows 路径不会
// 被当成转义序列），只有单引号本身需要写两遍。
// yamlSingleQuoted emits a single-quoted YAML scalar, keeping backslashes literal.
func yamlSingleQuoted(text string) string {
	return "'" + strings.ReplaceAll(text, "'", "''") + "'"
}

// instanceBootstrapReport 是一次新实例预检的结果。
// instanceBootstrapReport describes one bootstrap attempt.
type instanceBootstrapReport struct {
	// Fresh 表示本次确实是新实例（库与名册都不存在）；生成失败时仍为 true——
	// 调用方据此判断"要不要按新实例口径初始化加密身份"。
	Fresh bool
	// ConfigCreated / MarkerCreated 分别表示本次真的写出了对应文件。
	ConfigCreated bool
	MarkerCreated bool
	// InstanceID 是新生成的实例标识（ConfigCreated / MarkerCreated 为假时可能为空）。
	InstanceID string
}

// detectNewInstance 按唯一口径判定新实例：库与名册都不存在。
// detectNewInstance reports whether both the database and the roster are absent.
func detectNewInstance(workDir string) (bool, error) {
	dbPresent, err := pathExists(filepath.Join(workDir, workspaceDirName, databaseFileName))
	if err != nil {
		return false, err
	}
	if dbPresent {
		return false, nil
	}
	markerPresent, err := pathExists(instanceMarkerPath(workDir))
	if err != nil {
		return false, err
	}
	return !markerPresent, nil
}

// ensureNewInstanceConfig 为新实例补齐最小配置与名册；已存在的文件一字节不改。
//
// 并发首启：两个进程同时走到这里时，配置与名册都按 `O_CREAT|O_EXCL` 写，只有一个成功，
// 另一个按 EEXIST 直接装载既有文件——**不覆盖、不报错**。名册的标识因此全局唯一。
// ensureNewInstanceConfig fills the minimal config and the roster for a new instance and
// never rewrites an existing file; concurrent first starts converge on one winner.
func ensureNewInstanceConfig(workDir, runtimeRoot string) (instanceBootstrapReport, error) {
	report := instanceBootstrapReport{}
	fresh, err := detectNewInstance(workDir)
	if err != nil {
		return report, err
	}
	if !fresh {
		return report, nil
	}
	report.Fresh = true

	base, err := os.OpenRoot(workDir)
	if err != nil {
		return report, fmt.Errorf("打开工作目录 %s: %w", workDir, err)
	}
	defer func() { _ = base.Close() }()

	// 名册要落在工作区根下：目录先建（与 workspace.Init 同权限，init 随后会记 Kept）。
	// The workspace directory must exist before the roster can be written.
	if err := base.MkdirAll(workspaceDirName, 0o750); err != nil {
		return report, fmt.Errorf("创建工作区目录 %s: %w", workspaceDirName, err)
	}

	// ① 配置先写（见文件头：次序本身就是"崩溃不跳步"的保证）。
	created, err := createExclusiveFile(base, configFileName,
		[]byte(instanceConfigTemplate(runtimeRoot, workDir)))
	if err != nil {
		return report, fmt.Errorf("生成新实例配置 %s: %w", configFileName, err)
	}
	report.ConfigCreated = created

	// ② 名册后写：标识只在本进程真正写出时才有意义（EEXIST 说明别人已经写好）。
	id, err := newInstanceID()
	if err != nil {
		return report, err
	}
	marker := instanceMarker{Version: instanceMarkerVersion, InstanceID: id}
	raw, err := marshalInstanceMarker(marker)
	if err != nil {
		return report, err
	}
	created, err = createExclusiveFile(base, filepath.Join(workspaceDirName, instanceMarkerFileName), raw)
	if err != nil {
		return report, fmt.Errorf("写入实例名册 %s: %w", instanceMarkerFileName, err)
	}
	report.MarkerCreated = created
	if created {
		report.InstanceID = id
	} else if winner, present, readErr := readInstanceMarker(workDir); readErr == nil && present {
		// 另一个进程抢先写了名册：以**盘上的那个**为准（标识不可变）。
		report.InstanceID = winner.InstanceID
	}
	return report, nil
}

// marshalInstanceMarker 序列化名册（缩进 + 尾换行，便于人工核对与 diff）。
// marshalInstanceMarker renders the roster with indentation and a trailing newline.
func marshalInstanceMarker(marker instanceMarker) ([]byte, error) {
	raw, err := json.MarshalIndent(marker, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("序列化实例名册: %w", err)
	}
	return append(raw, '\n'), nil
}

// createExclusiveFile 以 `O_CREAT|O_EXCL` 写一个文件：已存在返回 `(false, nil)`——
// 并发首启的"输家"走的就是这条路，它随后装载既有文件，绝不覆盖。
// createExclusiveFile creates a file exclusively; EEXIST is a benign loss of the race.
func createExclusiveFile(base *os.Root, name string, content []byte) (bool, error) {
	file, err := base.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if errors.Is(err, fs.ErrExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if _, err := file.Write(content); err != nil {
		// 写坏的半截文件也要关掉；文件本身保留（删掉会让"是谁写的"变成不可证明）。
		_ = file.Close()
		return false, err
	}
	return true, file.Close()
}

// pathExists 报告路径是否存在（跟随链接）；不存在的错误不外抛。
// pathExists reports whether the path exists, following symlinks.
func pathExists(path string) (bool, error) {
	_, err := os.Stat(path)
	if err == nil {
		return true, nil
	}
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return false, fmt.Errorf("检查 %s: %w", path, err)
}
