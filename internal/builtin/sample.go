package builtin

// 本文件是样例库与 DBHub 只读配置的生成面：`basalt demo install` 与首次启动的自动准备
// 共用同一份脚本、同一份模板与同一个落点——两条路径各写一份配置只会让"装好的东西"和
// "自动准备的东西"慢慢分家。
//
// 生成结果如实三态：新建 / 已存在（逐字节未动）/ 待生成（缺解释器或脚本失败），
// 后者**不**让调用方失败——样例库是业务 Demo 的输入，不是服务启动的前提。
// The sample database and the DBHub read-only config are generated from one script and
// one template shared by the demo command and the first-start installer; a missing
// interpreter is reported as pending instead of aborting the caller.

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/ymedword/basalt/examples"
)

// StatePending 表示本次没有产出（缺解释器 / 脚本失败）；与 StateInstalled / StateKept
// 一起构成生成结果的三态。
// StatePending means nothing was produced this run.
const StatePending = "pending"

// pythonProbe 是解释器探针的固定脚本：只打印主版本号，用来识破 Windows 上
// "LookPath 成功但执行即退出"的 Microsoft Store 占位程序。
// pythonProbe prints only the major version so the Store stub is detected.
const pythonProbe = "import sqlite3, sys; print(sys.version_info[0])"

// SampleDBPath 是样例库的固定落点（生成、配置、报告共用一份来源）。
// SampleDBPath is the single source of the sample database location.
func SampleDBPath(wsRoot string) string {
	return filepath.Join(wsRoot, "samples", "biz-sample.db")
}

// DBHubConfigPath 是 DBHub 只读配置的固定落点。
// DBHubConfigPath is the single source of the dbhub.toml location.
func DBHubConfigPath(wsRoot string) string {
	return filepath.Join(wsRoot, "demos", "mcp", "dbhub.toml")
}

// dbhubConfigText 是配置正文模板（%s 处填 DSN）：1.5.0 的只读面与行数上限只能写在
// 配置里，`--readonly` 启动参数在该版本已被移除（2026-10-26 实测）。
// dbhubConfigText is the config body; %s is the DSN literal.
const dbhubConfigText = `# @bytebase/dbhub 1.5.0 的只读配置（由 Basalt 安装器生成）。
# Read-only DBHub config generated by the Basalt installer.
[[sources]]
id = "default"
dsn = %s

[[tools]]
name = "execute_sql"
source = "default"
readonly = true
max_rows = 500
`

// DBHubConfig 按样例库路径渲染只读配置。
// DBHubConfig renders the read-only config for the given sample database.
func DBHubConfig(dbPath string) string {
	return fmt.Sprintf(dbhubConfigText, strconv.Quote(dbhubDSN(dbPath)))
}

// dbhubDSN 把数据库路径转成 DBHub 1.5.0 接受的 SQLite DSN，规则与其自带的
// path→DSN 构造一致：`sqlite://` 后接「本来就有前导斜杠的路径」，没有前导斜杠
// （Windows 盘符）才补一个。
//
// **不得**写成 `"sqlite:///" + 路径`：POSIX 绝对路径自带 `/`，拼出 4 个斜杠后
// DBHub 用 URL 解析把 `//home/…` 当成网络位置样式，再去掉两个斜杠，变成相对路径
// `home/…`，报 `unable to open database file`（WSL2 实测，2026-10-27）。
// dbhubDSN mirrors DBHub's own path→DSN construction; a fourth slash makes DBHub
// parse `//home/...` as a relative path and fail to open the database on POSIX.
func dbhubDSN(dbPath string) string {
	slash := filepath.ToSlash(dbPath)
	if strings.HasPrefix(slash, "/") {
		return "sqlite://" + slash
	}
	return "sqlite:///" + slash
}

// EnsureDBHubConfig 写只读配置：已存在且不覆盖时返回 (路径, StateKept)。
// EnsureDBHubConfig writes the read-only config unless it already exists.
func EnsureDBHubConfig(wsRoot, dbPath string, force bool) (path, state string, err error) {
	target := DBHubConfigPath(wsRoot)
	if _, statErr := os.Stat(target); statErr == nil && !force {
		return target, StateKept, nil
	} else if statErr != nil && !errors.Is(statErr, fs.ErrNotExist) {
		return "", "", fmt.Errorf("检查 DBHub 配置 %s：%w", target, statErr)
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o750); err != nil {
		return "", "", fmt.Errorf("创建配置目录 %s：%w", filepath.Dir(target), err)
	}
	if err := os.WriteFile(target, []byte(DBHubConfig(dbPath)), 0o600); err != nil {
		return "", "", fmt.Errorf("写出 DBHub 配置 %s：%w", target, err)
	}
	return target, StateInstalled, nil
}

// FindPython 依次尝试 python3 / python / py——与 SETUP 里教用户的口径一致。
// 命中的候选必须**跑一次探针**（版本号 3 且能 import sqlite3）：Windows 的
// `python` 常是 Microsoft Store 的占位程序，LookPath 成功而执行即退出 9009——
// 直接采信 LookPath 会把「没有解释器」误报成「脚本失败」。
// FindPython probes the three documented names and requires each candidate to
// actually run; on Windows `python` is often the Store stub.
func FindPython(ctx context.Context) (string, error) {
	var failures []string
	for _, name := range []string{"python3", "python", "py"} {
		resolved, err := exec.LookPath(name)
		if err != nil {
			continue
		}
		// #nosec G204 -- 豁免理由（用户 2026-10-26 裁决）：可执行名来自本次
		// LookPath，实参全是常量（-c + pythonProbe）；探针的目的正是判断这个
		// 候选"能不能跑"，所以名字必然是运行期值，无法写成常量。
		// #nosec G204 -- the name is this loop's LookPath result; all argv are constants.
		output, probeErr := exec.CommandContext(ctx, resolved, "-c", pythonProbe).CombinedOutput()
		if probeErr != nil {
			failures = append(failures, fmt.Sprintf("%s 不可执行（%v）", resolved, probeErr))
			continue
		}
		if strings.TrimSpace(string(output)) != "3" {
			failures = append(failures, fmt.Sprintf("%s 不是 Python 3", resolved))
			continue
		}
		return resolved, nil
	}
	if len(failures) == 0 {
		return "", errors.New("PATH 里没有 python3 / python / py")
	}
	return "", errors.New(strings.Join(failures, "；"))
}

// SampleDB 记录样例库的生成结果；State 取 installed / kept / pending。
// SampleDB records the sample-database outcome.
type SampleDB struct {
	Path  string
	State string
	Note  string
}

// EnsureSampleDB 用内嵌脚本生成只读样例库；缺 Python 时记 pending 而不失败。
// 夹具取自已装好的 `agents/biz-daily/fixtures`——调用方必须先装 Agent（Install）。
// EnsureSampleDB generates the sample database from the installed biz-daily fixtures;
// a missing interpreter is reported as pending rather than aborting the caller.
func EnsureSampleDB(ctx context.Context, wsRoot string, force bool) (SampleDB, error) {
	dbPath := SampleDBPath(wsRoot)
	if _, err := os.Stat(dbPath); err == nil && !force {
		return SampleDB{Path: dbPath, State: StateKept}, nil
	}
	interpreter, err := FindPython(ctx)
	if err != nil {
		return SampleDB{Path: dbPath, State: StatePending, Note: "未找到可用的 Python 3：" + err.Error()}, nil
	}
	scriptDir := filepath.Join(wsRoot, "demos", "scripts")
	if err := os.MkdirAll(scriptDir, 0o750); err != nil {
		return SampleDB{}, fmt.Errorf("创建脚本目录 %s：%w", scriptDir, err)
	}
	scriptPath := filepath.Join(scriptDir, "make_sample_db.py")
	script, err := fs.ReadFile(examples.Assets, "shared/scripts/make_sample_db.py")
	if err != nil {
		return SampleDB{}, fmt.Errorf("读取样例库脚本：%w", err)
	}
	if err := os.WriteFile(scriptPath, script, 0o600); err != nil {
		return SampleDB{}, fmt.Errorf("写出样例库脚本 %s：%w", scriptPath, err)
	}
	if err := os.MkdirAll(filepath.Dir(dbPath), 0o750); err != nil {
		return SampleDB{}, fmt.Errorf("创建样例目录 %s：%w", filepath.Dir(dbPath), err)
	}
	fixtures := filepath.Join(wsRoot, agentsDirName, "biz-daily", "fixtures")
	args := []string{
		scriptPath,
		"--schema", filepath.Join(fixtures, "schema.sql"),
		"--rows", filepath.Join(fixtures, "rows.json"),
		"--out", dbPath,
	}
	if force {
		args = append(args, "--force")
	}
	// #nosec G204 -- 豁免理由（用户 2026-10-26 裁决，沿用 2026-10-17 口径）：
	// ① 可执行名是 FindPython 实跑探针通过的 LookPath 结果（候选只有 python3 /
	// python / py），argv 是安装器自己拼的脚本路径与内嵌夹具，不经 shell；
	// ② G204 只接受常量实参，运行期的工作区路径静态不可见，无法用代码消除；
	// ③ 改走 env 传参或动态分派只会把审计点藏起来，风险不变、可读性更差。
	// #nosec G204 -- vetted interpreter plus installer-built argv, never via a shell.
	output, runErr := exec.CommandContext(ctx, interpreter, args...).CombinedOutput()
	if runErr != nil {
		return SampleDB{
			Path:  dbPath,
			State: StatePending,
			Note:  fmt.Sprintf("生成失败（%v）：%s", runErr, strings.TrimSpace(string(output))),
		}, nil
	}
	return SampleDB{Path: dbPath, State: StateInstalled, Note: DescribeSampleDBNote(string(output))}, nil
}

// DescribeSampleDBNote 把生成器的 JSON 摘要压成一行事实（表名 / 行数 / 库哈希前
// 12 位）；摘要不是 JSON 时原样保留——宁可不美化，也不编造读数。
// DescribeSampleDBNote condenses the generator's JSON summary into one factual line.
func DescribeSampleDBNote(output string) string {
	var summary struct {
		Table string `json:"table"`
		Rows  struct {
			Count int `json:"count"`
		} `json:"rows"`
		DB struct {
			SHA256 string `json:"sha256"`
		} `json:"db"`
	}
	if err := json.Unmarshal([]byte(output), &summary); err != nil {
		return FirstLine(strings.TrimSpace(output))
	}
	hash := summary.DB.SHA256
	if len(hash) > 12 {
		hash = hash[:12] + "…"
	}
	return fmt.Sprintf("%s 表 %d 行，库 sha256 %s", summary.Table, summary.Rows.Count, hash)
}

// FirstLine 取多行输出的第一行（样例库脚本会打印 JSON 摘要）。
// FirstLine keeps the first line of a multi-line tool output.
func FirstLine(text string) string {
	if index := strings.IndexByte(text, '\n'); index >= 0 {
		return text[:index]
	}
	return text
}
